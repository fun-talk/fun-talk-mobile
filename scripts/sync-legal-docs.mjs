#!/usr/bin/env node
/**
 * Copies the legal pages from fun-talk-web (the single source of truth that is
 * served at https://ai-fun-talk.com/legal/*.html and submitted to app stores)
 * into src/features/legal/legalDocsBundled.generated.ts.
 *
 * The app loads the online page first; the bundled copy is only the offline
 * fallback, so it must stay byte-identical to the web files.
 *
 *   npm run sync:legal            # regenerate
 *   npm run sync:legal -- --check # exit 1 if the bundled copy is out of date
 *
 * The web repo is expected next to this one (../fun-talk-web); override with
 * FUN_TALK_WEB_DIR=/path/to/fun-talk-web.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = resolve(process.env.FUN_TALK_WEB_DIR ?? resolve(mobileRoot, '../fun-talk-web'));
const legalDir = resolve(webRoot, 'public/legal');
const outFile = resolve(mobileRoot, 'src/features/legal/legalDocsBundled.generated.ts');

const DOCS = {
  user: 'user-agreement.html',
  privacy: 'privacy-policy.html',
  children: 'children-privacy.html',
};

if (!existsSync(legalDir)) {
  console.error(`[sync-legal-docs] Web legal folder not found: ${legalDir}`);
  console.error('Set FUN_TALK_WEB_DIR to the fun-talk-web checkout.');
  process.exit(1);
}

const entries = Object.entries(DOCS).map(([type, file]) => {
  const html = readFileSync(resolve(legalDir, file), 'utf8');
  return `  ${type}: ${JSON.stringify(html)},`;
});

const output = `// AUTO-GENERATED by scripts/sync-legal-docs.mjs from fun-talk-web/public/legal.
// Do not edit by hand: change the web page, then run \`npm run sync:legal\`.
import type { LegalDocType } from './legalDocs';

export const BUNDLED_LEGAL_DOCS: Record<LegalDocType, string> = {
${entries.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('[sync-legal-docs] Bundled legal docs are out of date. Run `npm run sync:legal`.');
    process.exit(1);
  }
  console.log('[sync-legal-docs] Bundled legal docs match fun-talk-web.');
} else {
  writeFileSync(outFile, output);
  console.log(`[sync-legal-docs] Wrote ${outFile}`);
}
